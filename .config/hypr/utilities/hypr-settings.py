#!/usr/bin/env python3
"""Backend for the Hyprland settings panel.

Every style/variant keeps its own tweaks in hypr/tweaks/<Style>-<variant>.json (source of truth). The
active one is mirrored to hypr/settings.lua, which overrides.lua layers over the profile. Profile files
are never edited, and switching profile swaps in that profile's own tweaks.

  hypr-settings.py state KEY...      current values + profiles, themes and cursors, as JSON
  hypr-settings.py set KEY=JSON ...  save and live-apply (KEY is a dotted path, e.g. config.general.gaps_in;
                                     a JSON null removes the key)
  hypr-settings.py reset             drop the active profile's tweaks and go back to its own values
  hypr-settings.py sync              write settings.lua for the active profile (used when switching)
  hypr-settings.py cursor            apply the active profile's cursor theme and size
  hypr-settings.py ui KEY=JSON ...   panel UI state (width, last page), kept outside the repo
"""
import json
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HYPR = Path(__file__).resolve().parent.parent
HOME = Path.home()
TWEAKS = HYPR / "tweaks"
LUA_FILE = HYPR / "settings.lua"
THEME_FILE = HYPR / ".color-theme"
PROFILE_FILE = HYPR / ".active-profile"
SCHEMES = HOME / ".config/wal/colorschemes"
# Files pywal16 maintains itself for --cols16; not user-selectable themes.
INTERNAL_SCHEMES = {"pywal16", "ywal16"}
UI_FILE = HOME / ".local/state/hypr-settings/ui.json"
CURSOR_DIRS = [HOME / ".icons", HOME / ".local/share/icons", Path("/usr/share/icons")]


def run(*cmd):
    return subprocess.run(cmd, capture_output=True, text=True).stdout


def load(path, default):
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError):
        return default


def write_atomic(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text)
    tmp.replace(path)


def lua(value, depth=0):
    pad = "    " * (depth + 1)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, list):
        return "{ " + ", ".join(lua(v, depth) for v in value) + " }"
    items = "".join(f"{pad}[{json.dumps(k)}] = {lua(v, depth + 1)},\n" for k, v in sorted(value.items()))
    return "{\n" + items + "    " * depth + "}"


def tweaks_file():
    active = PROFILE_FILE.read_text().strip() if PROFILE_FILE.exists() else "default"
    return TWEAKS / (active.replace("/", "-") + ".json")


def save(settings):
    path = tweaks_file()
    if settings:
        write_atomic(path, json.dumps(settings, indent=2, sort_keys=True) + "\n")
        write_atomic(LUA_FILE, "-- Generated by utilities/hypr-settings.py; do not edit.\nreturn " + lua(settings) + "\n")
    else:
        path.unlink(missing_ok=True)
        write_atomic(LUA_FILE, "return {}\n")


def prune(tree):
    """Drop empty branches left behind after removing a key."""
    for key in [k for k, v in tree.items() if isinstance(v, dict)]:
        prune(tree[key])
        if not tree[key]:
            del tree[key]


def reapply(reload=False):
    run("hyprctl", "eval", 'package.loaded.settings=nil package.loaded.overrides=nil require("overrides")')
    if reload:
        run("hyprctl", "reload", "config-only")


def startup_defaults():
    """The profile's own boot and cursor values, read from the loaded startup.lua."""
    code = ('local d=require("startup").defaults '
            'return string.format("%s %d %s %d", tostring(d.boot.enabled), d.boot.black_ms, d.cursor.theme, d.cursor.size)')
    parts = run("hyprctl", "repl", code).split()
    if len(parts) == 4:
        return {"boot": {"enabled": parts[0] == "true", "black_ms": int(parts[1])},
                "cursor": {"theme": parts[2], "size": int(parts[3])}}
    return {"boot": {"enabled": True, "black_ms": 100}, "cursor": {"theme": "default", "size": 16}}


def option(path):
    raw = run("hyprctl", "getoption", "-j", path.replace(".", ":"))
    try:
        data = json.loads(raw)
    except ValueError:
        return None
    for kind in ("bool", "int", "float"):
        if kind in data:
            return data[kind]
    for kind in ("str", "custom", "css"):
        if kind in data:
            text = data[kind]
            if kind == "css":
                nums = text.split()
                return int(nums[0]) if nums and len(set(nums)) == 1 and nums[0].lstrip("-").isdigit() else text
            return "" if text == "[[EMPTY]]" else text
    return None


def dig(tree, dotted):
    for part in dotted.split("."):
        if not isinstance(tree, dict) or part not in tree:
            return None
        tree = tree[part]
    return tree


def profiles():
    found = {}
    for style in sorted(HYPR.iterdir()):
        if not (style / "utilities").is_dir():
            continue
        variants = sorted(v.name for v in style.iterdir() if (v / "hyprland.lua").is_file())
        if variants:
            found[style.name] = variants
    active = PROFILE_FILE.read_text().strip() if PROFILE_FILE.exists() else ""
    style, _, variant = active.partition("/")
    return found, {"style": style, "variant": variant}


def themes():
    out = []
    for path in sorted(SCHEMES.glob("*/*.json")):
        if path.stem in INTERNAL_SCHEMES:
            continue
        data = load(path, {})
        colors = data.get("colors", {})
        swatch = [data.get("special", {}).get("background")] + [colors.get(f"color{i}") for i in (1, 2, 3, 4, 5, 6, 9)]
        out.append({"id": f"{path.parent.name}/{path.stem}",
                    "name": path.stem.replace("-", " ").replace("_", " ").title(),
                    "swatch": [c for c in swatch if c]})
    return out


def waybar():
    """Waybar styles shipped by the active style, and which one is live (matched by file content)."""
    style = PROFILE_FILE.read_text().strip().partition("/")[0] if PROFILE_FILE.exists() else ""
    live = HOME / ".config/waybar"
    styles, active = [], ""
    for d in sorted((HYPR / style / "waybar").glob("*/")):
        if not (d / "config").is_file():
            continue
        styles.append({"id": d.name, "name": d.name.replace("-", " ").title(),
                       "image": str(d / "preview.png") if (d / "preview.png").is_file() else ""})
        same = all((d / f).read_bytes() == (live / g).read_bytes()
                   for f, g in (("config", "config"), ("style.css", "style.css"))
                   if (d / f).is_file() and (live / g).is_file())
        if same and not active:
            active = d.name
    return {"styles": styles, "active": active}


def cursors():
    names = {d.name for base in CURSOR_DIRS if base.is_dir() for d in base.iterdir() if (d / "cursors").is_dir()}
    return sorted(names, key=str.lower)


def mice():
    devices = json.loads(run("hyprctl", "devices", "-j") or "{}")
    return [m["name"] for m in devices.get("mice", []) if "touchpad" not in m["name"]]


def has_touchpad():
    devices = json.loads(run("hyprctl", "devices", "-j") or "{}")
    return any("touchpad" in m["name"] for m in devices.get("mice", []))


def monitor_count():
    return len(json.loads(run("hyprctl", "monitors", "-j") or "[]"))


def wallpaper_palette(path):
    """The 16-color pywal palette of the current wallpaper, from the wallpaper picker's index."""
    for entry in load(HOME / ".cache/wallpaper-picker/index.json", []):
        if entry.get("path") == path:
            return entry.get("colors", [])
    colors = load(HOME / ".cache/wal/colors.json", {}).get("colors", {})
    return [colors.get(f"color{i}") for i in range(16) if colors.get(f"color{i}")]


# Shown when a tweak has not been saved yet; the panel edits from these.
FALLBACKS = {
    "animation.preset": "theme",
    "animation.speed": 1.0,
    "animation.curve": [0.15, 0.85, 0.25, 1.0],
    "animation.window": "popin 90%",
    "animation.workspace": "slide",
    "border.gradient": False,
    "border.palette": "accent",
    "border.angle": 45,
}


def cmd_state(keys):
    settings = load(tweaks_file(), {})
    defaults = None
    values = {}
    live = [k for k in keys if k.startswith("config.")]
    with ThreadPoolExecutor(8) as pool:
        for key, value in zip(live, pool.map(lambda k: option(k[len("config."):]), live)):
            values[key] = value
    for key in keys:
        if key.startswith("config."):
            continue
        value = dig(settings, key)
        if value is None:
            if key.startswith(("boot.", "cursor.")):
                defaults = defaults or startup_defaults()
                value = dig(defaults, key)
            else:
                value = FALLBACKS.get(key)
        values[key] = value
    styles, active = profiles()
    colors = THEME_FILE.read_text().strip() if THEME_FILE.exists() else "pywal"
    wallpaper = (HOME / ".cache/wallpaper-picker/current").read_text().strip() if (HOME / ".cache/wallpaper-picker/current").exists() else ""
    print(json.dumps({
        "values": values,
        "styles": styles,
        "active": active,
        "themes": themes(),
        "colorTheme": colors or "pywal",
        "wallpaper": wallpaper,
        "pywalPalette": wallpaper_palette(wallpaper),
        "caps": {"touchpad": has_touchpad(), "multimonitor": monitor_count() > 1},
        "cursors": cursors(),
        "waybar": waybar(),
    }))


# Turning these off must hand control back to the profile, which only a config reload does.
RELOAD_ON_CHANGE = {"border.gradient"}


def cmd_set(pairs):
    settings = load(tweaks_file(), {})
    reload = False
    for pair in pairs:
        key, _, raw = pair.partition("=")
        value = json.loads(raw)
        node = settings
        *parents, leaf = key.split(".")
        for part in parents:
            node = node.setdefault(part, {})
        if value is None:
            node.pop(leaf, None)
            reload = True
        else:
            node[leaf] = value
        if key in RELOAD_ON_CHANGE and not value:
            reload = True
        if key == "config.input.sensitivity":
            settings["mice"] = mice()
    prune(settings)
    save(settings)
    reapply(reload)
    if any(p.startswith("cursor.") for p in pairs):
        cmd_cursor()


def cmd_reset():
    save({})
    reapply(reload=True)
    cmd_cursor()


def cmd_sync():
    settings = load(tweaks_file(), {})
    write_atomic(LUA_FILE, "-- Generated by utilities/hypr-settings.py; do not edit.\nreturn " + lua(settings) + "\n" if settings else "return {}\n")


def cmd_cursor():
    """Applies the active profile's cursor: its saved tweak, else the profile's own default."""
    cursor = load(tweaks_file(), {}).get("cursor", {})
    fallback = startup_defaults()["cursor"]
    run("hyprctl", "setcursor", cursor.get("theme", fallback["theme"]), str(cursor.get("size", fallback["size"])))


def cmd_ui(pairs):
    ui = load(UI_FILE, {})
    for pair in pairs:
        key, _, raw = pair.partition("=")
        ui[key] = json.loads(raw)
    write_atomic(UI_FILE, json.dumps(ui))


def main():
    command, args = (sys.argv[1], sys.argv[2:]) if len(sys.argv) > 1 else ("", [])
    handlers = {"state": cmd_state, "set": cmd_set, "ui": cmd_ui}
    bare = {"reset": cmd_reset, "sync": cmd_sync, "cursor": cmd_cursor}
    if command in bare:
        bare[command]()
    elif command in handlers:
        handlers[command](args)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
