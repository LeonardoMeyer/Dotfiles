#!/usr/bin/env python3

import json
import os
import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HYPR = Path(__file__).resolve().parent.parent
HOME = Path.home()
TWEAKS = HYPR / "tweaks"
LUA_FILE = HYPR / "settings.lua"
SAVED = TWEAKS / "saved"
ACTIVE_SAVED_FILE = HYPR / ".active-saved.json"
THEME_FILE = HYPR / ".color-theme"
PROFILE_FILE = HYPR / ".active-profile"
BAR_FILE = HYPR / ".active-bar"
QUICKSHELL_FILE = HYPR / ".quickshell-bar"
SCHEMES = HOME / ".config/wal/colorschemes"
# Files pywal16 maintains itself for --cols16; not user-selectable themes.
INTERNAL_SCHEMES = {"pywal16", "ywal16"}
UI_FILE = HOME / ".local/state/hypr-settings/ui.json"
CURSOR_DIRS = [HOME / ".icons", HOME / ".local/share/icons", Path("/usr/share/icons")]


def run(*cmd):
    return subprocess.run(cmd, capture_output=True, text=True).stdout


def load(path, default):
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError):
        return default


def write_atomic(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text)
    tmp.replace(path)


def lua(value, depth=0):
    pad = "    " * (depth + 1)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, list):
        return "{ " + ", ".join(lua(v, depth) for v in value) + " }"
    items = "".join(f"{pad}[{json.dumps(k)}] = {lua(v, depth + 1)},\n" for k, v in sorted(value.items()))
    return "{\n" + items + "    " * depth + "}"


def active_profile():
    return PROFILE_FILE.read_text().strip() if PROFILE_FILE.exists() else "default"


def tweaks_file(variant=None):
    style, _, own = active_profile().partition("/")
    return TWEAKS / f"{style}-{variant or own}.json"


def saved_dir():
    return SAVED / active_profile().replace("/", "-")


def own_variant():
    return "variant:" + active_profile().partition("/")[2]


def entry_file(entry):
    """The JSON behind a list entry; None for Default, which has no overrides."""
    kind, _, name = entry.partition(":")
    if kind == "variant":
        return tweaks_file(name)
    if kind == "saved":
        return saved_dir() / f"{name}.json"
    return None


def live_entry():
    mark = load(ACTIVE_SAVED_FILE, {}).get(active_profile(), "")
    if mark and ":" not in mark and mark != "default":
        mark = "saved:" + mark  # written by the first version, which only knew saved names
    if mark == "default" or (mark and entry_file(mark) and entry_file(mark).is_file()):
        return mark
    return own_variant() if tweaks_file().is_file() else "default"


def set_live_entry(entry):
    marks = load(ACTIVE_SAVED_FILE, {})
    marks[active_profile()] = entry
    write_atomic(ACTIVE_SAVED_FILE, json.dumps(marks, indent=2, sort_keys=True) + "\n")


def live_settings():
    path = entry_file(live_entry())
    return load(path, {}) if path else {}


def write_lua(settings):
    write_atomic(LUA_FILE, "-- Generated by utilities/hypr-settings.py; do not edit.\nreturn " + lua(settings) + "\n"
                 if settings else "return {}\n")


def portable(settings):
    """Wallpaper paths are kept as /home/$USER/... so the tweaks files work under any account."""
    path = dig(settings, "wallpaper.path")
    if isinstance(path, str):
        settings["wallpaper"]["path"] = re.sub(r"^/home/[^/]+/", "/home/$USER/", path)
    return settings


def save(settings):
    """An edit lands in the live entry and it stays live; on Default it goes to the active variant's own file."""
    entry = live_entry()
    if entry == "default":
        entry = own_variant()
    # Written even when empty, so a profile whose last tweak was removed stays listed and selected.
    write_atomic(entry_file(entry), json.dumps(portable(settings), indent=2, sort_keys=True) + "\n")
    set_live_entry(entry)
    write_lua(settings)


def prune(tree):
    """Drop empty branches left behind after removing a key."""
    for key in [k for k, v in tree.items() if isinstance(v, dict)]:
        prune(tree[key])
        if not tree[key]:
            del tree[key]


def reapply(reload=False):
    run("hyprctl", "eval", 'package.loaded.settings=nil package.loaded.overrides=nil require("overrides")')
    if reload:
        run("hyprctl", "reload", "config-only")


def startup_defaults():
    """The profile's own boot and cursor values, read from the loaded startup.lua."""
    code = ('local d=require("startup").defaults '
            'return string.format("%s %d %s %d", tostring(d.boot.enabled), d.boot.black_ms, d.cursor.theme, d.cursor.size)')
    parts = run("hyprctl", "repl", code).split()
    if len(parts) == 4:
        return {"boot": {"enabled": parts[0] == "true", "black_ms": int(parts[1])},
                "cursor": {"theme": parts[2], "size": int(parts[3])}}
    return {"boot": {"enabled": True, "black_ms": 100}, "cursor": {"theme": "default", "size": 16}}


def glass_defaults():
    """hyprglass.lua's preset values ("key" and "dark.key"/"light.key"), read from the loaded config."""
    code = ('local g=package.loaded.hyprglass if type(g)~="table" then return "" end local o={} '
            'for k,v in pairs(g.values) do if type(v)=="table" then '
            'for k2,v2 in pairs(v) do o[#o+1]=k.."."..k2.."="..tostring(v2) end '
            'elseif type(v)~="string" then o[#o+1]=k.."="..tostring(v) end end return table.concat(o," ")')
    out = {}
    for pair in run("hyprctl", "repl", code).split():
        key, _, raw = pair.partition("=")
        try:
            out[key] = json.loads(raw)
        except ValueError:
            pass
    return out


def option(path):
    raw = run("hyprctl", "getoption", "-j", path.replace(".", ":"))
    try:
        data = json.loads(raw)
    except ValueError:
        return None
    for kind in ("bool", "int", "float"):
        if kind in data:
            return data[kind]
    for kind in ("str", "custom", "css"):
        if kind in data:
            text = data[kind]
            if kind == "css":
                nums = text.split()
                return int(nums[0]) if nums and len(set(nums)) == 1 and nums[0].lstrip("-").isdigit() else text
            return "" if text == "[[EMPTY]]" else text
    return None


def dig(tree, dotted):
    for part in dotted.split("."):
        if not isinstance(tree, dict) or part not in tree:
            return None
        tree = tree[part]
    return tree


def profiles():
    found = {}
    for style in sorted(HYPR.iterdir()):
        if not (style / "utilities").is_dir():
            continue
        variants = sorted(v.name for v in style.iterdir() if (v / "machine.lua").is_file())
        if variants:
            found[style.name] = variants
    active = PROFILE_FILE.read_text().strip() if PROFILE_FILE.exists() else ""
    style, _, variant = active.partition("/")
    return found, {"style": style, "variant": variant}


def themes():
    out = []
    for path in sorted(SCHEMES.glob("*/*.json")):
        if path.stem in INTERNAL_SCHEMES:
            continue
        data = load(path, {})
        colors = data.get("colors", {})
        swatch = [data.get("special", {}).get("background")] + [colors.get(f"color{i}") for i in (1, 2, 3, 4, 5, 6, 9)]
        out.append({"id": f"{path.parent.name}/{path.stem}",
                    "name": path.stem.replace("-", " ").replace("_", " ").title(),
                    "swatch": [c for c in swatch if c]})
    return out


def style_dir():
    """hypr/<style> of the active profile."""
    return HYPR / (PROFILE_FILE.read_text().strip().partition("/")[0] if PROFILE_FILE.exists() else "")


def bar_styles(folder, marker):
    """A bar's styles shipped by the active style: hypr/<style>/<folder>/<name>/ holding `marker`, with an optional
    preview.svg or preview.png. Adding a style is just adding its folder."""
    out = []
    for d in sorted((style_dir() / folder).glob("*/")):
        if not (d / marker).is_file():
            continue
        image = next((d / f for f in ("preview.svg", "preview.png") if (d / f).is_file()), None)
        out.append({"id": d.name, "name": d.name.replace("-", " ").title(), "image": str(image) if image else ""})
    return out


def waybar():
    """Waybar styles, and which one is live (matched by file content)."""
    styles, live, base = bar_styles("waybar", "config"), HOME / ".config/waybar", style_dir() / "waybar"
    same = lambda s: all((base / s["id"] / f).read_bytes() == (live / f).read_bytes()
                         for f in ("config", "style.css") if (base / s["id"] / f).is_file() and (live / f).is_file())
    return {"styles": styles, "active": next((s["id"] for s in styles if same(s)), "")}


def quickshell():
    """Quickshell bar styles, and which one is live (hypr/.quickshell-bar names it; none named means "default")."""
    styles, live = bar_styles("quickshellbar", "config.json"), load_text(QUICKSHELL_FILE) or DEFAULT_QUICKSHELL
    return {"styles": styles, "active": live if any(s["id"] == live for s in styles) else ""}


def cursors():
    names = {d.name for base in CURSOR_DIRS if base.is_dir() for d in base.iterdir() if (d / "cursors").is_dir()}
    return sorted(names, key=str.lower)


def mice():
    devices = json.loads(run("hyprctl", "devices", "-j") or "{}")
    return [m["name"] for m in devices.get("mice", []) if "touchpad" not in m["name"]]


def has_touchpad():
    devices = json.loads(run("hyprctl", "devices", "-j") or "{}")
    return any("touchpad" in m["name"] for m in devices.get("mice", []))


def has_hyprglass():
    """Installed and loaded right now: the glass rows would do nothing otherwise."""
    return "hyprglass" in run("hyprctl", "plugin", "list").lower()


def monitor_count():
    return len(json.loads(run("hyprctl", "monitors", "-j") or "[]"))


def wallpaper_palette(path):
    """The 16-color pywal palette of the current wallpaper, from the wallpaper picker's index."""
    for entry in load(HOME / ".cache/wallpaper-picker/index.json", []):
        if entry.get("path") == path:
            return entry.get("colors", [])
    colors = load(HOME / ".cache/wal/colors.json", {}).get("colors", {})
    return [colors.get(f"color{i}") for i in range(16) if colors.get(f"color{i}")]


# Shown when a tweak has not been saved yet; the panel edits from these.
FALLBACKS = {
    "animation.preset": "theme",
    "utilities.animations": False,
    "animation.speed": 1.0,
    "animation.curve": [0.15, 0.85, 0.25, 1.0],
    "animation.window": "popin 90%",
    "animation.workspace": "slide",
    "border.gradient": False,
    "border.palette": "accent",
    "border.angle": 45,
}


def cmd_state(keys):
    settings = live_settings()
    defaults = None
    glass = None
    values = {}
    live = [k for k in keys if k.startswith("config.")]
    with ThreadPoolExecutor(8) as pool:
        for key, value in zip(live, pool.map(lambda k: option(k[len("config."):]), live)):
            values[key] = value
    for key in keys:
        if key.startswith("config."):
            continue
        value = dig(settings, key)
        if value is None:
            if key.startswith(("boot.", "cursor.")):
                defaults = defaults or startup_defaults()
                value = dig(defaults, key)
            elif key.startswith("glass."):
                # The preset's own value; a theme variant beats the shared one, as in the plugin.
                if glass is None:
                    glass = glass_defaults()
                    glass_theme = option("plugin.hyprglass.default_theme") or "dark"
                name = key[len("glass."):]
                value = glass.get(f"{glass_theme}.{name}", glass.get(name))
            elif key.startswith("hyprglass."):
                # Not split yet: the profile's layer glass covers both layers and Quickshell.
                value = bool(option("plugin.hyprglass.layers.enabled"))
            else:
                value = FALLBACKS.get(key)
        values[key] = value
    styles, active = profiles()
    colors = current_theme()
    wallpaper = current_wallpaper()
    print(json.dumps({
        "values": values,
        "styles": styles,
        "active": active,
        "themes": themes(),
        "colorTheme": colors or "pywal",
        "wallpaper": wallpaper,
        "pywalPalette": wallpaper_palette(wallpaper),
        "caps": {"touchpad": has_touchpad(), "multimonitor": monitor_count() > 1, "hyprglass": has_hyprglass()},
        "cursors": cursors(),
        "waybar": waybar(),
        "bar": current_bar(),
        "quickshell": quickshell(),
        "saved": saved_state(),
    }))


# Turning these off must hand control back to the profile, which only a config reload does.
RELOAD_ON_CHANGE = {"border.gradient"}


def cmd_set(pairs):
    # On Default the edit goes to the variant's tweaks, so build on them rather than replace them.
    settings = live_settings() if live_entry() != "default" else load(tweaks_file(), {})
    reload = False
    for pair in pairs:
        key, _, raw = pair.partition("=")
        value = json.loads(raw)
        node = settings
        *parents, leaf = key.split(".")
        for part in parents:
            node = node.setdefault(part, {})
        if value is None:
            node.pop(leaf, None)
            reload = True
        else:
            node[leaf] = value
        if key in RELOAD_ON_CHANGE and not value:
            reload = True
        # Presets and layer namespace lists are only committed by a config reload.
        if key.startswith(("glass.", "hyprglass.")):
            reload = True
        if key == "config.input.sensitivity":
            settings["mice"] = mice()
    prune(settings)
    save(settings)
    reapply(reload)
    if any(p.startswith("cursor.") for p in pairs):
        cmd_cursor()


def cmd_reset():
    go_live("default")


def cmd_sync():
    write_lua(live_settings())


def cmd_cursor():
    """Applies the active profile's cursor: its saved tweak, else the profile's own default."""
    cursor = live_settings().get("cursor", {})
    fallback = startup_defaults()["cursor"]
    run("hyprctl", "setcursor", cursor.get("theme", fallback["theme"]), str(cursor.get("size", fallback["size"])))


def saved_name(raw):
    """Names become file names: letters, digits, spaces, dashes and underscores, up to 40 characters."""
    name = " ".join("".join(c for c in raw if c.isalnum() or c in " -_").split())[:40]
    if not name:
        sys.exit("saved profile needs a name")
    return name


def saved_state():
    """Default, then every variant of the active style, then the saved profiles."""
    style = active_profile().partition("/")[0]
    entries = [{"id": "default", "name": "Default", "kind": "default", "exists": True}]
    for variant in profiles()[0].get(style, []):
        entries.append({"id": "variant:" + variant, "name": variant.capitalize(), "kind": "variant",
                        "exists": tweaks_file(variant).is_file()})
    for name in sorted((p.stem for p in saved_dir().glob("*.json")), key=str.lower):
        entries.append({"id": "saved:" + name, "name": name, "kind": "saved", "exists": True})
    return {"entries": entries, "active": live_entry()}


DEFAULT_THEME = "pywal"
DEFAULT_WAYBAR = "default"
DEFAULT_BAR = "waybar"
DEFAULT_QUICKSHELL = "default"


WALLPAPER_FILE = HOME / ".cache/wallpaper-picker/current"


def current_wallpaper():
    return WALLPAPER_FILE.read_text().strip() if WALLPAPER_FILE.exists() else ""


def current_bar():
    """waybar or quickshell, as bar.sh last set it."""
    return "quickshell" if load_text(BAR_FILE) == "quickshell" else DEFAULT_BAR


def current_theme():
    return (THEME_FILE.read_text().strip() if THEME_FILE.exists() else "") or DEFAULT_THEME


def detached(*cmd, env=None):
    subprocess.Popen(cmd, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                     start_new_session=True, env={**os.environ, **(env or {})})


def real_wallpaper(path):
    """The image itself, never wallpaper-apply.sh's ~/wallpapers/pywallpaper.jpg copy."""
    if path and Path(path).name == "pywallpaper.jpg":
        path = next((p for p in (current_wallpaper(), load_text(HOME / ".cache/wal/wal"))
                     if p and Path(p).name != "pywallpaper.jpg"), path)
    return path if path and Path(path).is_file() else ""


def load_text(path):
    try:
        return path.read_text().strip()
    except OSError:
        return ""


def cmd_appearance():
    """Wallpaper, colors, the bar and its styles follow the live entry. The wallpaper is re-run on every switch
    (the entry's own, else the one already up), which also regenerates the palette; waybar only restarts when it
    changes."""
    settings = live_settings()
    theme = dig(settings, "colors.theme") or DEFAULT_THEME
    wallpaper = real_wallpaper(os.path.expandvars(dig(settings, "wallpaper.path") or "")) or real_wallpaper(current_wallpaper())
    if wallpaper:
        # wallpaper-apply.sh regenerates the palette with the saved theme, so set that first. Re-running it
        # is not a new pick, so it must not be recorded (on Default that would switch to the variant).
        write_atomic(THEME_FILE, theme + "\n")
        detached(str(HYPR / "utilities/wallpaper-apply.sh"), wallpaper, env={"HYPR_SETTINGS_NO_RECORD": "1"})
    elif theme != current_theme():
        detached(str(HYPR / "utilities/color-apply.sh"), theme)
    # The bar is switched first and waited on, so the waybar style below sees which bar is up.
    kind = dig(settings, "bar.kind") or DEFAULT_BAR
    if kind != current_bar():
        subprocess.run([str(HYPR / "utilities/bar.sh"), "apply", kind], env={**os.environ, "HYPR_SETTINGS_NO_RECORD": "1"},
                       stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    look = dig(settings, "quickshell.style") or DEFAULT_QUICKSHELL
    qs = quickshell()
    if look != qs["active"] and any(s["id"] == look for s in qs["styles"]):
        detached(str(HYPR / "utilities/bar.sh"), "style", look, env={"HYPR_SETTINGS_NO_RECORD": "1"})
    bar = waybar()
    # While the quickshell bar is up, waybar keeps its default config and style.
    style = DEFAULT_WAYBAR if kind == "quickshell" else dig(settings, "waybar.style") or DEFAULT_WAYBAR
    if style != bar["active"] and any(s["id"] == style for s in bar["styles"]):
        detached(str(HYPR / "utilities/waybar-style.sh"), "apply", style, env={"HYPR_SETTINGS_NO_RECORD": "1"})


def go_live(entry):
    set_live_entry(entry)
    write_lua(live_settings())
    reapply(reload=True)
    cmd_cursor()
    cmd_appearance()


def cmd_saved(args):
    action, raw = (args + ["", ""])[:2]
    if action == "save":
        name = saved_name(raw)
        # The snapshot keeps the colors and waybar on screen, even where the live entry relies on the defaults.
        snapshot = live_settings()
        snapshot.setdefault("colors", {})["theme"] = current_theme()
        if current_wallpaper():
            snapshot.setdefault("wallpaper", {})["path"] = current_wallpaper()
        if waybar()["active"]:
            snapshot.setdefault("waybar", {})["style"] = waybar()["active"]
        snapshot.setdefault("bar", {})["kind"] = current_bar()
        look = quickshell()["active"]
        if look:
            snapshot.setdefault("quickshell", {})["style"] = look
        write_atomic(saved_dir() / f"{name}.json", json.dumps(portable(snapshot), indent=2, sort_keys=True) + "\n")
        set_live_entry("saved:" + name)
    elif action == "apply":
        path = entry_file(raw)
        if raw != "default" and not (path and (path.is_file() or raw == own_variant())):
            sys.exit(f"nothing to apply for {raw}")
        go_live(raw)
    elif action == "delete":
        path = entry_file(raw)
        if path is None:
            sys.exit("Default can't be deleted")
        was_live = live_entry() == raw
        path.unlink(missing_ok=True)
        if was_live:
            go_live("default")
    elif action == "wipe":
        for path in list(SAVED.glob("*/*.json")) + list(TWEAKS.glob("*.json")):
            path.unlink()
        for d in SAVED.glob("*/"):
            d.rmdir()
        ACTIVE_SAVED_FILE.unlink(missing_ok=True)
        go_live("default")
    else:
        sys.exit(__doc__)


def cmd_ui(pairs):
    ui = load(UI_FILE, {})
    for pair in pairs:
        key, _, raw = pair.partition("=")
        ui[key] = json.loads(raw)
    write_atomic(UI_FILE, json.dumps(ui))


def main():
    command, args = (sys.argv[1], sys.argv[2:]) if len(sys.argv) > 1 else ("", [])
    handlers = {"state": cmd_state, "set": cmd_set, "ui": cmd_ui, "saved": cmd_saved}
    bare = {"reset": cmd_reset, "sync": cmd_sync, "cursor": cmd_cursor, "appearance": cmd_appearance}
    if command in bare:
        bare[command]()
    elif command in handlers:
        handlers[command](args)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
